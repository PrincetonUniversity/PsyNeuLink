"""Option 1: does the exact-vs-NLE gap close as dt shrinks?

The confirmatory DDM data is generated by Euler-Maruyama at dt=0.01, KDE and NLE both target that
same discrete process, but "exact" (Navarro-Fuss WFPT) is the continuous-time limit.  If that
model mismatch is why NLE edged out exact, then shrinking dt should converge Euler-Maruyama onto
the continuum and *close the gap*.

Paired design: identical true parameters at every dt, so differences are attributable to dt alone.
Each dt gets its OWN trained NLE (the net must learn the process that actually made the data).

  python dt_convergence_study.py --dts 0.01 0.001
"""
import argparse
import json
import os
import sys
import time

import numpy as np

_HERE = os.path.dirname(os.path.abspath(__file__))
_PARENT = os.path.dirname(_HERE)
for _d in ("core", "nle"):
    p = os.path.join(_PARENT, _d)
    if p not in sys.path:
        sys.path.append(p)

import neural_likelihood as nl
from transforms import BoundedTransform
from laplace_em import fit_laplace_em

OUT_DIR = "/scratch/gpfs/JDC/ap9344/ddm_dt_convergence"
STIMULI = np.array([-2.0, -1.0, -0.5, 0.5, 1.0, 2.0])
RATE_RANGE = (-1.5, 1.5)
THRESH_RANGE = (0.28, 1.55)
GROUP_MEAN = np.array([0.0, 0.9])     # natural (rate, threshold)
GROUP_SD_Z = np.array([0.36, 0.36])   # unconstrained-space SD


def fit_box():
    return np.array([RATE_RANGE[0], THRESH_RANGE[0]]), np.array([RATE_RANGE[1], THRESH_RANGE[1]])


def make_training_set_dt(n_configs, trials_per_config, rng, dt):
    """nl.make_training_set, but with dt threaded through (the module default is fixed at 0.01)."""
    drift = rng.uniform(*nl.DRIFT_RANGE, size=n_configs).repeat(trials_per_config)
    thresh = rng.uniform(*nl.THRESH_RANGE, size=n_configs).repeat(trials_per_config)
    choice, fpt, valid = nl.simulate_ddm(drift, thresh, rng, dt=dt)
    drift, thresh, choice, fpt = drift[valid], thresh[valid], choice[valid], fpt[valid]
    drift = np.concatenate([drift, -drift])
    thresh = np.concatenate([thresh, thresh])
    choice = np.concatenate([choice, 1 - choice])
    fpt = np.concatenate([fpt, fpt])
    return drift, thresh, choice, fpt


def generate_dataset(theta_true, stim_seq, rng, dt):
    """Simulate one dataset (subjects x trials) at this dt from fixed true parameters."""
    n_subjects = theta_true.shape[0]
    n_trials = len(stim_seq)
    choice = np.empty((n_subjects, n_trials), dtype=np.int8)
    rt = np.empty((n_subjects, n_trials))
    for s in range(n_subjects):
        drift = theta_true[s, 0] * stim_seq
        thresh = np.full(n_trials, theta_true[s, 1])
        c, fpt, valid = nl.simulate_ddm(drift, thresh, rng, dt=dt)
        # resample the rare non-absorbed paths so every trial has an outcome
        tries = 0
        while not valid.all() and tries < 50:
            idx = np.flatnonzero(~valid)
            c2, f2, v2 = nl.simulate_ddm(drift[idx], thresh[idx], rng, dt=dt)
            c[idx], fpt[idx], valid[idx] = c2, f2, v2
            tries += 1
        fpt = np.where(np.isfinite(fpt), fpt, np.nanmedian(fpt[np.isfinite(fpt)]))
        choice[s], rt[s] = c, fpt + nl.NDT
    return choice, rt


def exact_loglik_factory(choice, rt, stim_seq):
    def loglik(theta, s):
        return float(nl.wfpt_logpdf(rt[s], choice[s], theta[0] * stim_seq, theta[1]).sum())
    return loglik


def nle_loglik_factory(net, choice, rt, stim_seq):
    def loglik(theta, s):
        n = len(stim_seq)
        return float(net.trial_log_density(theta[0] * stim_seq, np.full(n, theta[1]),
                                           choice[s], rt[s]).sum())
    return loglik


def run(args):
    import torch
    os.makedirs(OUT_DIR, exist_ok=True)
    lo, hi = fit_box()
    tf = BoundedTransform(lo, hi)
    beta_z = tf.to_unconstrained(GROUP_MEAN)

    # --- fixed across dt: true subject parameters + stimulus sequence (paired design) ---
    truth_rng = np.random.default_rng(args.seed)
    stim_seq = truth_rng.choice(STIMULI, size=args.num_trials)
    theta_true_sets = []
    for d in range(args.datasets):
        z = truth_rng.normal(beta_z, GROUP_SD_Z, size=(args.n_subjects, 2))
        theta_true_sets.append(np.array([tf.to_natural(z[s]) for s in range(args.n_subjects)]))

    rows = []
    for dt in args.dts:
        print(f"\n{'='*66}\ndt = {dt}\n{'='*66}", flush=True)
        # --- train an NLE for THIS dt ---
        t0 = time.time()
        tr_rng = np.random.default_rng(9000 + int(round(1 / dt)))
        drift, thresh, ch, fpt = make_training_set_dt(args.nle_configs, args.nle_trials, tr_rng, dt)
        cond = np.stack([drift, thresh], axis=1)
        torch.manual_seed(0)
        net = nl.DDMMixtureNet(n_comp=8, n_inputs=2)
        nl.fit(net, cond, ch, fpt, epochs=args.nle_epochs, log=lambda *a, **k: None)
        net.eval()
        print(f"  NLE trained on {len(ch):,} rows in {time.time()-t0:.0f}s", flush=True)

        for d in range(args.datasets):
            theta_true = theta_true_sets[d]
            gen_rng = np.random.default_rng(int(1e6) + d * 100 + int(round(1 / dt)))
            choice, rt = generate_dataset(theta_true, stim_seq, gen_rng, dt)

            for method, factory in (("exact", exact_loglik_factory(choice, rt, stim_seq)),
                                    ("nle", nle_loglik_factory(net, choice, rt, stim_seq))):
                t1 = time.time()
                r = fit_laplace_em(factory, args.n_subjects, 2, tf,
                                   max_em_iterations=args.em_iters, em_tol=1e-4,
                                   variance_floor=1e-6, hessian_step=0.05)
                rmse = float(np.sqrt(np.mean((r.theta_hat - theta_true) ** 2)))
                per = np.sqrt(np.mean((r.theta_hat - theta_true) ** 2, axis=0))
                rows.append(dict(dt=dt, dataset=d, method=method, rmse=rmse,
                                 rmse_rate=float(per[0]), rmse_threshold=float(per[1]),
                                 converged=bool(r.converged), n_iter=int(r.n_iter),
                                 seconds=time.time() - t1))
                print(f"  ds{d} {method:6s} RMSE={rmse:.4f} "
                      f"(rate {per[0]:.4f} / thr {per[1]:.4f})  {time.time()-t1:.0f}s", flush=True)

    with open(f"{OUT_DIR}/results.json", "w") as fh:
        json.dump(rows, fh, indent=1)

    # --- summary: the paired gap at each dt ---
    print(f"\n{'='*66}\nSUMMARY: mean RMSE by dt (paired on the same true parameters)\n{'='*66}")
    print(f"{'dt':>8s} {'exact':>10s} {'nle':>10s} {'gap (exact-nle)':>17s}")
    for dt in args.dts:
        e = [r["rmse"] for r in rows if r["dt"] == dt and r["method"] == "exact"]
        n = [r["rmse"] for r in rows if r["dt"] == dt and r["method"] == "nle"]
        if e and n:
            print(f"{dt:8g} {np.mean(e):10.4f} {np.mean(n):10.4f} {np.mean(e)-np.mean(n):17.4f}")
    print("\nPREDICTION: if the exact-vs-NLE gap is caused by the discrete-time mismatch,")
    print("the gap should SHRINK toward 0 as dt decreases.")
    print(f"\nwrote {OUT_DIR}/results.json")


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--dts", type=float, nargs="+", default=[0.01, 0.001])
    p.add_argument("--datasets", type=int, default=6)
    p.add_argument("--n_subjects", type=int, default=16)
    p.add_argument("--num_trials", type=int, default=200)
    p.add_argument("--nle_configs", type=int, default=3000)
    p.add_argument("--nle_trials", type=int, default=60)
    p.add_argument("--nle_epochs", type=int, default=25)
    p.add_argument("--em_iters", type=int, default=30)
    p.add_argument("--seed", type=int, default=4242)
    run(p.parse_args())
